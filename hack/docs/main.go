// Command docs writes the generated pages of the documentation site:
// docs/reference/metrics.md, from the metrics the operator registers. The
// API reference (docs/reference/api.md) comes from crd-ref-docs; see
// `make docs-reference`.
package main

import (
	"bytes"
	"fmt"
	"os"
	"strings"

	"github.com/MohanadAbugharbia/odoo-operator/internal/metrics"
)

func main() {
	if len(os.Args) != 2 {
		fmt.Fprintln(os.Stderr, "usage: docs <metrics.md>")
		os.Exit(2)
	}
	docs, err := metrics.Reference()
	if err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
	var b bytes.Buffer
	b.WriteString(`<!-- Generated by hack/docs from internal/metrics; run make docs-reference. Do not edit. -->
# Metrics

The manager serves these on ` + "`/metrics`" + ` beside the controller-runtime
defaults; [Monitoring and alerts](../guides/monitoring.md) shows how to scrape
them.

- Series marked *scrape time* are read from the status of every
  OdooDeployment and OdooBackupStore when Prometheus scrapes. Only the elected
  leader reports them, and a deleted object disappears on the next scrape.
- The others count events, each once, on the reconcile that causes it: a Job
  that stays failed, an image that keeps failing to pull or a drop that keeps
  failing is not counted again on every requeue. The per-OdooDeployment
  counters start at 0 and are removed once the OdooDeployment is gone.

| Metric | Type | Labels | Description |
|---|---|---|---|
`)
	for _, d := range docs {
		labels := "—"
		if len(d.Labels) > 0 {
			labels = "`" + strings.Join(d.Labels, "`, `") + "`"
		}
		help := strings.ReplaceAll(d.Help, "|", `\|`)
		if d.ScrapeTime {
			help += " *(scrape time)*"
		}
		fmt.Fprintf(&b, "| `%s` | %s | %s | %s |\n", d.Name, d.Type, labels, help)
	}
	if err := os.WriteFile(os.Args[1], b.Bytes(), 0o644); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}
